#!/usr/bin/env bash
# =============================================================================
#  웹캠 손추적 — 화면만 (로봇 미연결). 가장 안전한 시작점입니다.
# =============================================================================
set -u
cd "$(dirname "$(readlink -f "$0")")"
CAMERA=0
[ -x .venv/bin/python ] || { echo "먼저 ./설치.sh 를 실행하십시오."; read -r; exit 1; }

echo "=============================================================="
echo " 웹캠 손추적 (로봇 미연결 — 화면만)"
echo "=============================================================="
./.venv/bin/python src/hand_tracking_control.py --list-cameras || { read -r; exit 1; }
echo
echo "  창이 열리면 손바닥을 카메라 쪽으로 보여 주십시오."
echo "  조작 : q 종료 | c 가동범위 초기화 | space 일시정지 | o 손 펴기"
echo "=============================================================="
echo
./.venv/bin/python src/hand_tracking_control.py --source "$CAMERA" --backend none "$@"
echo
read -r -p "창을 닫으려면 엔터를 누르십시오. "
